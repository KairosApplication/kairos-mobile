package com.example.kairos.view

import android.os.Bundle
import android.text.InputType
import android.widget.*
import android.view.View
import android.graphics.BitmapFactory
import androidx.activity.result.contract.ActivityResultContracts
import androidx.appcompat.app.AppCompatActivity
import androidx.appcompat.app.AlertDialog
import androidx.core.content.FileProvider
import androidx.core.content.res.ResourcesCompat
import androidx.lifecycle.ViewModelProvider
import com.example.kairos.R
import com.example.kairos.model.scanner.*
import com.example.kairos.viewmodel.*
import com.google.firebase.auth.FirebaseAuth
import java.io.File
import java.util.UUID

/** Catalog, review and explicit stock confirmation around the lifecycle-bound CameraX capture. */
class ScannerActivity : AppCompatActivity() {
    private lateinit var vm: ScannerViewModel
    private lateinit var body: LinearLayout
    private var pendingPhoto: File? = null
    private var owner: String? = null
    private var confirmation: AlertDialog? = null
    private var productId: Long? = null
    private var inventoryId: Long? = null
    private var quantity = ""
    private var damages = "0"
    private val authListener = FirebaseAuth.AuthStateListener { auth ->
        if (owner != null && auth.currentUser?.uid != owner) { confirmation?.dismiss(); vm.reset(); finish() }
    }
    private val capture = registerForActivityResult(ActivityResultContracts.StartActivityForResult()) { result ->
        val file = pendingPhoto
        pendingPhoto = null
        if (result.resultCode == RESULT_OK && file != null && file.exists()) vm.photo(file)
        else { file?.delete(); vm.error("Captura cancelada ou câmera indisponível. Você pode tentar novamente.") }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        window.addFlags(android.view.WindowManager.LayoutParams.FLAG_SECURE)
        vm = ViewModelProvider(this)[ScannerViewModel::class.java]
        owner = FirebaseAuth.getInstance().currentUser?.uid
        if (owner == null) { finish(); return }
        val pendingStore = getSharedPreferences("pending-restocking", MODE_PRIVATE)
        val persisted = runCatching { org.json.JSONObject(pendingStore.getString(owner, null) ?: "") }.getOrNull()
        persisted?.let { row -> runCatching {
            vm.recover(owner!!, ConfirmedRestocking(row.getString("commandId"), row.getLong("shelfId"), row.getLong("inventoryId"),
                row.getLong("productId"), row.getInt("quantity"), row.getInt("damages")))
        } }
        FirebaseAuth.getInstance().addAuthStateListener(authListener)
        val directory = File(cacheDir, "scanner").apply { mkdirs() }
        // Remove abandoned captures on a new scanner session. Names and paths are generated by this app.
        if (savedInstanceState == null) directory.listFiles()?.filter { it.isFile }?.forEach { it.delete() }
        if (savedInstanceState != null && savedInstanceState.getString("owner") == owner) {
            savedInstanceState.getString("pendingPhoto")?.takeIf { it.matches(Regex("[a-f0-9-]+\\.jpg")) }
                ?.let { pendingPhoto = File(directory, it) }
            productId = savedInstanceState.getLong("productId").takeIf { it > 0 }
            inventoryId = savedInstanceState.getLong("inventoryId").takeIf { it > 0 }
            quantity = savedInstanceState.getString("quantity").orEmpty()
            damages = savedInstanceState.getString("damages") ?: "0"
        }
        body = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(24, 48, 24, 24)
            fitsSystemWindows = true
        }
        setContentView(ScrollView(this).apply { isFillViewport = true; addView(body) })
        vm.state.observe(this, ::render)
        vm.account(owner!!)
    }

    override fun onSaveInstanceState(outState: Bundle) {
        outState.putString("owner", owner)
        outState.putString("pendingPhoto", pendingPhoto?.name)
        outState.putLong("productId", productId ?: 0)
        outState.putLong("inventoryId", inventoryId ?: 0)
        outState.putString("quantity", quantity)
        outState.putString("damages", damages)
        super.onSaveInstanceState(outState)
    }
    private fun label(value: String, title: Boolean = false) = TextView(this).apply {
        text = value; textSize = if (title) 24f else 16f
        typeface = ResourcesCompat.getFont(this@ScannerActivity, if (title) R.font.montserrat_semibold else R.font.montserrat_regular)
        setTextColor(if (vm.state.value?.step == ScannerStep.RESULT) getColor(R.color.home_ink) else android.graphics.Color.WHITE)
        setPadding(0, 12, 0, 12)
    }
    private fun button(value: String, enabled: Boolean = true, action: () -> Unit) {
        body.addView(Button(this).apply {
            text = value; isEnabled = enabled
            typeface = ResourcesCompat.getFont(this@ScannerActivity, R.font.montserrat_semibold)
            isAllCaps = false
            backgroundTintList = android.content.res.ColorStateList.valueOf(getColor(R.color.home_button))
            setTextColor(getColor(R.color.home_button_text)); setOnClickListener { action() }
        })
    }
    private fun choices(prompt: String, entries: List<CatalogItem>, selected: Long?, changed: (Long?) -> Unit) {
        body.addView(label(prompt))
        val values = listOf(CatalogItem(0, "Selecione…")) + entries
        body.addView(Spinner(this).apply {
            adapter = ArrayAdapter(this@ScannerActivity, android.R.layout.simple_spinner_dropdown_item, values)
            setSelection(values.indexOfFirst { it.id == selected }.coerceAtLeast(0))
            onItemSelectedListener = object : android.widget.AdapterView.OnItemSelectedListener {
                override fun onNothingSelected(parent: android.widget.AdapterView<*>?) = Unit
                override fun onItemSelected(parent: android.widget.AdapterView<*>?, view: View?, position: Int, id: Long) {
                    val value = values[position].id.takeIf { it > 0 }
                    if (value != selected) changed(value)
                }
            }
        })
    }
    private fun number(prompt: String, current: String, changed: (String) -> Unit) {
        body.addView(label(prompt))
        body.addView(EditText(this).apply {
            inputType = InputType.TYPE_CLASS_NUMBER; isSaveEnabled = false; setText(current)
            filters = arrayOf(android.text.InputFilter.LengthFilter(10))
            addTextChangedListener(object : android.text.TextWatcher {
                override fun beforeTextChanged(s: CharSequence?, start: Int, count: Int, after: Int) = Unit
                override fun onTextChanged(s: CharSequence?, start: Int, before: Int, count: Int) { changed(s.toString()) }
                override fun afterTextChanged(s: android.text.Editable?) = Unit
            })
        })
    }
    private fun takePhoto() {
        val file = File(File(cacheDir, "scanner"), "${UUID.randomUUID()}.jpg")
        pendingPhoto?.delete(); pendingPhoto = file
        try { capture.launch(android.content.Intent(this, ShelfCameraActivity::class.java).putExtra("filename", file.name)) }
        catch (_: android.content.ActivityNotFoundException) { pendingPhoto = null; file.delete(); vm.error("Nenhum aplicativo de câmera disponível.") }
        catch (_: SecurityException) { pendingPhoto = null; file.delete(); vm.error("A câmera não recebeu acesso à captura. Tente novamente.") }
    }
    private fun render(state: ScannerState) {
        if (FirebaseAuth.getInstance().currentUser?.uid != owner) return
        val store = getSharedPreferences("pending-restocking", MODE_PRIVATE)
        state.pending?.let { request ->
            // Non-secret command data only; account-scoped and excluded from device backups.
            store.edit().putString(owner, org.json.JSONObject().put("commandId", request.commandId).put("shelfId", request.shelfId)
                .put("inventoryId", request.inventoryId).put("productId", request.productId).put("quantity", request.quantity)
                .put("damages", request.damages).toString()).commit()
        }
        if (state.step == ScannerStep.COMPLETE || state.step == ScannerStep.RESULT && state.pending == null && !state.loading)
            store.edit().remove(owner).apply()
        body.removeAllViews()
        body.setPadding(24, 48, 24, 24)
        body.background = if (state.step == ScannerStep.RESULT) android.graphics.drawable.ColorDrawable(getColor(R.color.home_surface))
            else android.graphics.drawable.GradientDrawable(android.graphics.drawable.GradientDrawable.Orientation.TOP_BOTTOM,
                intArrayOf(getColor(R.color.home_header_top), getColor(R.color.home_header_middle), getColor(R.color.home_header_top)))
        if (state.loading) {
            body.setPadding(0, 0, 0, 0)
            if (state.step == ScannerStep.START) {
                body.addView(label("Carregando catálogo autorizado…")); body.addView(ProgressBar(this))
            } else body.addView(AnalysisProgressView(this, state.step in setOf(ScannerStep.RESULT, ScannerStep.CONFIRMING)),
                    LinearLayout.LayoutParams(-1, resources.displayMetrics.heightPixels))
            return
        }
        body.addView(label(when {
            state.loading && state.step == ScannerStep.RESULT -> "Registrando reposição…"
            state.loading && state.step == ScannerStep.PREVIEW -> "Analisando gôndola…"
            state.step == ScannerStep.COMPLETE -> "Reposição concluída"
            state.step == ScannerStep.RESULT -> "Confira a análise"
            state.step == ScannerStep.IN_PROGRESS -> "Reposição em andamento"
            state.step == ScannerStep.CONFIRMING -> "Confirmar reposição"
            state.step == ScannerStep.PREVIEW -> "Confira a foto"
            else -> "Scanner de gôndolas"
        }, title = true))
        if (state.error.isNotBlank()) body.addView(label(state.error).apply { accessibilityLiveRegion = View.ACCESSIBILITY_LIVE_REGION_POLITE })
        if (state.step == ScannerStep.COMPLETE) {
            body.addView(ImageView(this).apply { setImageResource(R.drawable.scanner_check) },
                LinearLayout.LayoutParams(-1, (230 * resources.displayMetrics.density).toInt()).apply {
                    topMargin = (64 * resources.displayMetrics.density).toInt(); bottomMargin = (32 * resources.displayMetrics.density).toInt()
                })
            body.addView(label("O servidor confirmou a movimentação de estoque."))
            button("Concluir") { setResult(RESULT_OK); finish() }
            return
        }
        val catalog = state.catalog
        if (catalog == null) { button("Carregar dados novamente") { vm.retryCatalog() }; return }
        if (state.step in setOf(ScannerStep.IN_PROGRESS, ScannerStep.CONFIRMING)) {
            val request = state.draft ?: state.pending
            if (request == null) { button("Voltar") { finish() }; return }
            body.addView(label("Gôndola ${request.shelfId}\n${catalog.products.firstOrNull { it.id == request.productId }?.label.orEmpty()}\n" +
                "Estoque ${request.inventoryId}: ${request.quantity} unidades, incluindo ${request.damages} avarias.\n" +
                "Entrarão na gôndola ${request.quantity - request.damages} unidades."))
            if (state.step == ScannerStep.IN_PROGRESS) {
                body.addView(label("Realize a reposição física e confira as quantidades. O estoque ainda não foi movimentado no sistema."))
                button("Já repus — fotografar conferência") { takePhoto() }
                button("Cancelar sem registrar") { finish() }
            } else {
                state.photo?.let { file -> body.addView(ImageView(this).apply {
                    setImageBitmap(BitmapFactory.decodeFile(file.path, BitmapFactory.Options().apply { inSampleSize = 8 })); adjustViewBounds = true
                }, LinearLayout.LayoutParams(-1, (resources.displayMetrics.widthPixels * .9).toInt())) }
                body.addView(label("Você concluiu a reposição? A foto não comprova o saldo: confirme manualmente produto, gôndola, quantidade e avarias."))
                button(if (state.pending == null) "Confirmar reposição" else "Tentar a mesma confirmação novamente") {
                    vm.pending(request); vm.confirm(request)
                }
                if (state.pending == null) button("Fotografar novamente") { takePhoto() }
            }
            return
        }
        if (state.step == ScannerStep.START || state.step == ScannerStep.PREVIEW) {
            body.addView(label("Selecione uma gôndola atribuída a você. A foto será enviada ao serviço de IA e ao provedor Gemini para análise, sem armazenamento permanente no Kairos."))
            choices("Gôndola", catalog.shelves, state.shelfId, vm::shelf)
            if (state.photo != null) {
                val bitmap = BitmapFactory.decodeFile(state.photo.path, BitmapFactory.Options().apply { inSampleSize = 8 })
                body.addView(ImageView(this).apply { setImageBitmap(bitmap); adjustViewBounds = true },
                    LinearLayout.LayoutParams(-1, (resources.displayMetrics.widthPixels * 1.15).toInt()))
                button("Repetir foto") { takePhoto() }
                button("Enviar para análise", state.shelfId != null) { vm.analyze() }
            } else button("Abrir câmera", state.shelfId != null) { takePhoto() }
        } else if (state.step == ScannerStep.RESULT) {
            state.result?.warnings?.forEach { body.addView(label(it)) }
            if (state.result?.observations.isNullOrEmpty()) body.addView(label("Nenhum produto reconhecido. Repita a foto ou selecione manualmente um produto do catálogo."))
            state.result?.observations?.forEach { observation ->
                body.addView(label("${observation.name} ${observation.brand}\nConfiança: ${observation.confidence}. " +
                    "Quantidade visível estimada: ${observation.visibleQuantity?.toString() ?: "incerta"}. " +
                    if (observation.unrecognized || observation.candidates.isEmpty()) "Identificação não confirmada." else "Confira o produto no catálogo."))
            }
            body.addView(label("A foto não determina o saldo de estoque. Confirme um produto por operação; informe o total retirado do estoque e as avarias incluídas nesse total."))
            val pending = state.pending
            if (pending != null) {
                body.addView(label("A confirmação anterior pode ter sido recebida. A nova tentativa usará o mesmo identificador para impedir movimentação duplicada."))
                button("Tentar a mesma confirmação novamente") { vm.confirm(pending) }
            } else {
                button("Fotografar novamente") { takePhoto() }
                choices("Produto confirmado", catalog.products, productId) { productId = it }
                choices("Estoque de origem", catalog.inventories, inventoryId) { inventoryId = it }
                number("Quantidade retirada do estoque", quantity) { quantity = it }
                number("Avarias (incluídas no total)", damages) { damages = it }
                button("Iniciar reposição") {
                    try {
                        val request = vm.prepare(inventoryId ?: 0, productId ?: 0, quantity.toIntOrNull() ?: 0, damages.toIntOrNull() ?: -1)
                        confirmation = AlertDialog.Builder(this).setTitle("Conferir itens da reposição")
                            .setMessage("Gôndola ${request.shelfId}\n${catalog.products.first { it.id == request.productId }.label}\n" +
                                "Estoque ${request.inventoryId}: ${request.quantity} unidades, incluindo ${request.damages} avarias.\n" +
                                "Entrarão na gôndola ${request.quantity - request.damages} unidades.")
                            .setNegativeButton("Revisar", null).setPositiveButton("Iniciar reposição") { _, _ ->
                                vm.begin(request)
                            }.show()
                    } catch (_: IllegalArgumentException) { vm.error("Selecione produto e estoque; informe quantidade positiva e avarias entre zero e o total.") }
                }
            }
            button("Voltar") { finish() }
        }
    }
    override fun onDestroy() {
        confirmation?.dismiss()
        FirebaseAuth.getInstance().removeAuthStateListener(authListener)
        if (isFinishing) pendingPhoto?.delete()
        super.onDestroy()
    }
}
